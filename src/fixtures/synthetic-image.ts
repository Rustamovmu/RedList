import sharp from 'sharp';

/**
 * A generated test pattern (gradients and stripes) that stands in for a photograph in development and tests.
 * It is made here from nothing, so it has no third-party creator and no licence question: it is released as CC0.
 */
export async function syntheticImage(width = 1600, height = 1000, hue = 0): Promise<Buffer> {
  const raw = Buffer.alloc(width * height * 3);
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const i = (y * width + x) * 3;
      const band = Math.floor((x + y) / 40) % 2;
      raw[i] = (40 + (x * 120) / width + hue) % 256;
      raw[i + 1] = 90 + (y * 100) / height + band * 20;
      raw[i + 2] = (60 + ((width - x) * 60) / width + hue / 2) % 256;
    }
  }
  return sharp(raw, { raw: { width, height, channels: 3 } }).jpeg({ quality: 85 }).toBuffer();
}

