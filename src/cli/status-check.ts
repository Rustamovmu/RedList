/**
 * Hand-checked IUCN status (R1 launch readiness, DECISIONS D-032). See docs/launch/STATUS_CHECK.md.
 *
 *   npm run status:sheet                                   (re)build docs/launch/status-check.csv from the published
 *                                                          catalogue, keeping every value already filled in, and
 *                                                          refresh the table in docs/launch/STATUS_CHECK.md
 *   npm run status:import -- <sheet.csv> --dry-run         validate and report, write nothing
 *   npm run status:import -- <sheet.csv> --apply           write the checked rows into DRAFTS
 *
 * Nothing is ever submitted or published, and no value is ever filled in by this tool.
 */
import { loadDotEnv } from '../common/load-env';
loadDotEnv();
import { NestFactory } from '@nestjs/core';
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { basename, join } from 'node:path';
import { AppModule } from '../app.module';
import { DB, Db } from '../db/db.module';
import { EditorialService } from '../editorial/editorial.service';
import { RevisionContentRepository } from '../editorial/revision-content.repository';
import { importStaff } from '../import/importer';
import { buildSheet, readSheet, sheetMarkdownTable, StatusCheckError, StatusCheckImporter, statusReportMarkdown, toCsv } from '../import/status-check';

const DEFAULT_CSV = 'docs/launch/status-check.csv';
const DEFAULT_MD = 'docs/launch/STATUS_CHECK.md';
const START = '<!-- status-sheet:start (generated by npm run status:sheet; edit the CSV, not this table) -->';
const END = '<!-- status-sheet:end -->';

async function sheet(app: Awaited<ReturnType<typeof NestFactory.createApplicationContext>>, csvPath: string) {
  const previous = existsSync(csvPath) ? readSheet(await readFile(csvPath, 'utf8')) : [];
  const { rows, orphaned } = await buildSheet(app.get<Db>(DB), previous, { excludeFixtures: true });
  await writeFile(csvPath, toCsv(rows));
  console.log(`Wrote ${csvPath}: ${rows.length} row(s), ${rows.filter((r) => r.checked_category).length} filled in.`);
  if (orphaned.length) console.log(`Kept filled rows for species that are no longer published: ${orphaned.join(', ')}`);
  const missingIds = rows.filter((r) => !r.iucn_taxon_id).map((r) => r.slug);
  if (missingIds.length) console.log(`No IUCN taxon ID recorded for: ${missingIds.join(', ')}`);
  if (existsSync(DEFAULT_MD)) {
    const md = await readFile(DEFAULT_MD, 'utf8');
    const a = md.indexOf(START);
    const b = md.indexOf(END);
    if (a >= 0 && b > a) {
      await writeFile(DEFAULT_MD, `${md.slice(0, a + START.length)}\n${sheetMarkdownTable(rows)}\n${md.slice(b)}`);
      console.log(`Refreshed the table in ${DEFAULT_MD}.`);
    }
  }
}

async function importSheet(app: Awaited<ReturnType<typeof NestFactory.createApplicationContext>>, file: string, dryRun: boolean) {
  const db = app.get<Db>(DB);
  const importer = new StatusCheckImporter(db, app.get(EditorialService), app.get(RevisionContentRepository));
  const report = await importer.run(await importStaff(db), await readFile(file, 'utf8'), { dryRun, fileName: basename(file) });
  await mkdir('import-reports', { recursive: true });
  const out = join('import-reports', `${report.startedAt.replace(/[:.]/g, '-')}-status-check-${report.mode}.md`);
  await writeFile(out, statusReportMarkdown(report));
  console.log(`${report.mode}: ${report.changeCount} change(s); ${report.species.length} checked row(s), ${report.unchecked.length} not checked yet; report: ${out}`);
  for (const sp of report.species) for (const n of sp.notes) console.log(`Note (${sp.slug}): ${n}`);
}

async function main() {
  const [cmd, ...args] = process.argv.slice(2);
  const file = args.find((a) => !a.startsWith('--'));
  const flags = args.filter((a) => a.startsWith('--'));
  const usage = () => {
    console.error('Usage: npm run status:sheet [-- <sheet.csv>]\n       npm run status:import -- <sheet.csv> (--dry-run | --apply)');
    process.exit(2);
  };
  if (cmd === 'sheet') {
    if (flags.length) usage();
  } else if (cmd === 'import') {
    if (!file || flags.length !== 1 || !['--dry-run', '--apply'].includes(flags[0])) usage();
  } else usage();

  const app = await NestFactory.createApplicationContext(AppModule, { logger: ['error'] });
  try {
    if (cmd === 'sheet') await sheet(app, file ?? DEFAULT_CSV);
    else await importSheet(app, file as string, flags[0] === '--dry-run');
  } catch (e) {
    if (e instanceof StatusCheckError) {
      console.error(e.message);
      process.exitCode = 1;
    } else throw e;
  } finally {
    await app.close();
  }
}

if (require.main === module) {
  main().catch((e) => {
    console.error(e instanceof Error ? e.message : e);
    process.exit(1);
  });
}
